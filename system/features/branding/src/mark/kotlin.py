"""The mark's geometry as Kotlin data for SystemUI's moments (motion.md).

    python3 kotlin.py OUT.kt WORKDIR

Writes object SymbolData in SystemUI's package for the moments: the ten shards' facets, centres
and facet directions, the mark's outer and inner radius, and the canonical shard (one big shard
normalised: base middle at the origin, tip at (0, -1)), which the back gesture's arrowhead and the
volume float draw. Paths are command arrays (0 moveTo x y, 1 lineTo x y, 2 cubicTo x1 y1 x2 y2 x y,
3 close), so no SVG parser runs on the phone.
"""
import math
import pathlib
import re
import sys

import mark

OPS = {"M": (0, 2), "L": (1, 2), "C": (2, 6), "Z": (3, 0)}


def path_ops(d):
    toks = re.findall(r"[MLCZ]|-?\d+\.?\d*", d)
    out, i = [], 0
    while i < len(toks):
        op, n = OPS[toks[i]]
        args = [float(x) for x in toks[i + 1:i + 1 + n]]
        if len(args) != n:
            raise ValueError(f"bad path {d!r}")
        out.append(op)
        out.extend(args)
        i += 1 + n
    return out


def points(d):
    nums = [float(x) for x in re.findall(r"-?\d+\.\d+", d)]
    return list(zip(nums[0::2], nums[1::2]))


def canonical(facets):
    """The biggest shard normalised: base middle at the origin, tip at (0, -1); its facet paths,
    facet directions and base corners' half width."""
    big = max(facets, key=lambda s: math.hypot(s["tip"][0] - s["c"][0], s["tip"][1] - s["c"][1]))
    pts = points(big["fa"])
    tip, m = pts[0], pts[-1]                     # fa: M tip C c c b1 C c c m Z
    ux, uy = tip[0] - m[0], tip[1] - m[1]
    L = math.hypot(ux, uy)
    rot_by = -math.pi / 2 - math.atan2(uy, ux)

    def tr(p):
        x, y = p[0] - m[0], p[1] - m[1]
        c, s = math.cos(rot_by), math.sin(rot_by)
        return ((x * c - y * s) / L, (x * s + y * c) / L)

    def conv(d):
        toks = re.findall(r"[MLCZ]|-?\d+\.?\d*", d)
        out, buf = [], []
        for t in toks:
            if t in "MLCZ":
                out.append(t)
            else:
                buf.append(float(t))
                if len(buf) == 2:
                    q = tr(buf)
                    out.append(f"{q[0]:.4f} {q[1]:.4f}")
                    buf = []
        return " ".join(out)

    na = mark.rot_vec(big["na"], rot_by)
    nb = mark.rot_vec(big["nb"], rot_by)
    fa = conv(big["fa"])
    half = round(abs(points(fa)[3][0]), 3)       # b1, the base corner of facet a
    return (fa, conv(big["fb"]), [round(na[0], 4), round(na[1], 4)],
            [round(nb[0], 4), round(nb[1], 4)], half)


def fl(x):
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    if s in ("-0", ""):
        s = "0"
    return s + "f"


def db(x):
    s = repr(float(x))
    return "0.0" if s == "-0.0" else s


def farr(xs):
    return "floatArrayOf(" + ", ".join(fl(x) for x in xs) + ")"


def darr(xs):
    return "doubleArrayOf(" + ", ".join(db(x) for x in xs) + ")"


def source():
    F = mark.facets()
    outline = [p for s in F for p in points(s["fa"] + " " + s["fb"])]
    outer = round(max(math.hypot(x, y) for x, y in outline), 3)
    inner = round(min(min(math.hypot(x, y) for x, y in points(s["fa"] + " " + s["fb"])) for s in F), 3)
    ca, cb, cna, cnb, half = canonical(F)
    centre = [(round(s["c"][0], 3), round(s["c"][1], 3)) for s in F]
    na = [(round(s["na"][0], 4), round(s["na"][1], 4)) for s in F]
    nb = [(round(s["nb"][0], 4), round(s["nb"][1], 4)) for s in F]
    lines = [
        "// Generated by tools/lujarch from system/features/branding/src/mark.",
        "",
        "package com.android.systemui.surfaceeffects.lujarch",
        "",
        "/** The mark's geometry (BRD-3). */",
        "object SymbolData {",
        f"    const val SHARDS = {len(F)}",
        f"    const val OUTER_RADIUS = {db(outer)}",
        f"    const val INNER_RADIUS = {db(inner)}",
        "",
        "    const val MOVE = 0f",
        "    const val LINE = 1f",
        "    const val CUBIC = 2f",
        "    const val CLOSE = 3f",
        "",
        f"    @JvmField val CENTRE_X = {darr(c[0] for c in centre)}",
        f"    @JvmField val CENTRE_Y = {darr(c[1] for c in centre)}",
        f"    @JvmField val NORMAL_A_X = {darr(n[0] for n in na)}",
        f"    @JvmField val NORMAL_A_Y = {darr(n[1] for n in na)}",
        f"    @JvmField val NORMAL_B_X = {darr(n[0] for n in nb)}",
        f"    @JvmField val NORMAL_B_Y = {darr(n[1] for n in nb)}",
        "",
        "    @JvmField",
        "    val FACET_A: Array<FloatArray> =",
        "        arrayOf(",
    ]
    lines += [f"            {farr(path_ops(s['fa']))}," for s in F]
    lines += ["        )", "", "    @JvmField", "    val FACET_B: Array<FloatArray> =", "        arrayOf("]
    lines += [f"            {farr(path_ops(s['fb']))}," for s in F]
    lines += [
        "        )",
        "",
        f"    @JvmField val CANON_FACET_A = {farr(path_ops(ca))}",
        f"    @JvmField val CANON_FACET_B = {farr(path_ops(cb))}",
        f"    const val CANON_NORMAL_A_X = {db(cna[0])}",
        f"    const val CANON_NORMAL_A_Y = {db(cna[1])}",
        f"    const val CANON_NORMAL_B_X = {db(cnb[0])}",
        f"    const val CANON_NORMAL_B_Y = {db(cnb[1])}",
        f"    const val CANON_BASE_HALF_WIDTH = {db(half)}",
        "}",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    pathlib.Path(sys.argv[1]).write_text(source())
