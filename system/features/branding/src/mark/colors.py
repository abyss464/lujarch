"""The System updates card's colours in the mark's (BRD-3).

    python3 colors.py OUT.xml WORKDIR

The card's ground is the mark's red ochre, its pattern a little lighter, its sheen the light tone,
and the mark and the version on it the palette's specular white.
"""
import pathlib
import sys

import mark


def colors():
    entries = {
        "brand_primary": mark.COLOR,
        "brand_pattern": mark.mix(mark.COLOR, 0.2, "#ffffff"),
        "brand_sheen": mark.LIGHT,
        "on_brand_surface": mark.SPECULAR,
    }
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Generated by tools/lujarch from system/features/branding/src/mark. -->\n"
            "<resources>\n"
            + "".join(f'    <color name="{k}">{v.upper()}</color>\n' for k, v in entries.items())
            + "</resources>\n")


if __name__ == "__main__":
    pathlib.Path(sys.argv[1]).write_text(colors())
