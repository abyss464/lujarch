"""The mark as an Android vector drawable (BRD-3): the System updates card's mark.

    python3 vector.py OUT.xml WORKDIR

Every facet of the ten shards, filled in one colour, which the card tints; the viewport is the
mark's outer circle, so the drawable is as wide as it is tall.
"""
import math
import pathlib
import re
import sys

import mark


def drawable():
    F = mark.facets()
    pts = [float(x) for s in F for x in re.findall(r"-?\d+\.\d+", s["fa"] + " " + s["fb"])]
    r = max(math.hypot(x, y) for x, y in zip(pts[0::2], pts[1::2]))
    side = 2 * math.ceil(r)
    paths = "\n".join(
        f'        <path android:fillColor="#FFFFFFFF" android:pathData="{s[k]}" />'
        for s in F for k in ("fa", "fb"))
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/lujarch from system/features/branding/src/mark. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="120dp"
    android:height="120dp"
    android:viewportWidth="{side}"
    android:viewportHeight="{side}">
    <group
        android:translateX="{side // 2}"
        android:translateY="{side // 2}">
{paths}
    </group>
</vector>
'''


if __name__ == "__main__":
    pathlib.Path(sys.argv[1]).write_text(drawable())
